from __future__ import annotations

import re
from pathlib import Path
from typing import Any


class CapabilityMapGenerator:
    """
    Builds a live map of services, tools, endpoints, persona files, memories, tests,
    and connected services.
    """

    def __init__(self, project_root: Path) -> None:
        self.project_root = project_root

    def generate_map(self) -> dict[str, Any]:
        tools = self._scan_tools()
        services = self._scan_services()
        endpoints = self._scan_endpoints()
        personas = self._scan_personas()
        tests = self._scan_tests()

        return {
            "ok": True,
            "project_name": "Vaila OS V3",
            "tools_count": len(tools),
            "services_count": len(services),
            "endpoints_count": len(endpoints),
            "personas_count": len(personas),
            "tests_count": len(tests),
            "tools": tools,
            "services": services,
            "endpoints": endpoints,
            "personas": personas,
            "tests": tests
        }

