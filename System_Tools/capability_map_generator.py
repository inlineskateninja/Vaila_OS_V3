    def _scan_tools(self) -> list[dict[str, Any]]:
        tools = []
        tools_dir = self.project_root / "System_Tools"
        if not tools_dir.exists():
            return []

        for p in tools_dir.glob("*.py"):
            if p.stem == "__init__":
                continue
            
            content = p.read_text(encoding="utf-8", errors="replace")
            # Parse class name (e.g. class FileAnalyzer:)
            class_match = re.search(r"class\s+([A-Za-z0-9_]+)", content)
            class_name = class_match.group(1) if class_match else p.stem.title().replace("_", "")

            tools.append({
                "id": p.stem,
                "name": p.stem.replace("_", " ").title(),
                "file_name": p.name,
                "module_path": f"System_Tools.{p.stem}",
                "class_name": class_name
            })
        return tools

    def _scan_services(self) -> list[dict[str, Any]]:
        services = []
        services_dir = self.project_root / "System_Services"
        if not services_dir.exists():
            return []

        for p in services_dir.glob("*.py"):
            if p.stem == "__init__":
                continue

            content = p.read_text(encoding="utf-8", errors="replace")
            class_match = re.search(r"class\s+([A-Za-z0-9_]+)", content)
            class_name = class_match.group(1) if class_match else p.stem.title().replace("_", "")

            services.append({
                "id": p.stem,
                "class_name": class_name,
                "file_path": f"System_Services/{p.name}"
            })
        return services

    def _scan_endpoints(self) -> list[dict[str, Any]]:
        endpoints = []
        api_path = self.project_root / "Core_System_Files" / "local_api.py"
        if not api_path.exists():
            return []

        content = api_path.read_text(encoding="utf-8", errors="replace")
        
        # Look for router decorators, e.g. @app.get("/api/...") or @app.post("/chat")
        pattern = r"@app\.(get|post|put|delete|patch)\(\"([^\"]+)\"\)\n(?:async\s+)?def\s+([a-zA-Z0-9_]+)"
        matches = re.findall(pattern, content)
        for method, path, handler in matches:
            endpoints.append({
                "method": method.upper(),
                "path": path,
                "handler_name": handler
            })
        return endpoints

